package com.freeyou.data

data class MentorContext(
    val reasons: List<String>,
    val days: Int,
    val attempt: Int,
    val hour: Int
)

object MentorLines {

    private val OPEN_FIRST = listOf(
        "עצור רגע. אני החלק בך שקם מוקדם.",
        "חכה. זה אני, זה שרצה את כל זה מלכתחילה.",
        "לא ככה. אני מכיר אותך יותר טוב מהרגע הזה.",
        "תעצור. אני הצד בך שבונה, ואני עדיין כאן.",
        "רגע אחד. אני הקול שלך מהבוקר, לא זה של עכשיו."
    )

    private val OPEN_SECOND = listOf(
        "זו הפעם השנייה היום. אני לא מוותר עליך.",
        "שוב. ואני עדיין בצד שלך, וזה בדיוק למה אני לא אתן לזה לעבור.",
        "פעם שנייה. אז עכשיו נעשה את זה עם הגוף, לא עם המילים."
    )

    private val OPEN_NIGHT = listOf(
        "שלוש לפנות בוקר. אני מכיר את השעה הזו — היא לא מייעצת טוב.",
        "הלילה משקר לך. אני לא.",
        "בשעה הזו הכל נראה בלתי נמנע. זה לא."
    )

    private val TRUTH = listOf(
        "אתה לא רוצה את זה. אתה רוצה שיהיה קל, וזה לא אותו דבר.",
        "זה לא תשוקה. זו בריחה, ואתה יודע ממה.",
        "המוח שלך מבטיח לך משהו שהוא אף פעם לא סיפק.",
        "בעוד עשרים דקות אתה תהיה אדם אחר, לכיוון זה או השני. עכשיו זה נקבע.",
        "הדבר הזה לוקח ממך בדיוק את מה שאתה צריך כדי לבנות.",
        "תוך רבע שעה הגל הזה יורד לבד. אני רק צריך שתישאר איתי עד אז."
    )

    private val TRUTH_STREAK = listOf(
        "בנינו ביחד {days} ימים. אני לא נותן להם ללכת בשלוש דקות.",
        "{days} ימים אחורה עומדים כאן איתי. תסתכל עליהם.",
        "אתה כבר לא האיש שהתחיל. {days} ימים שינו משהו אמיתי."
    )

    private val ACTION_FIRST = listOf(
        "עכשיו תכתוב לי. שתי דקות, ואני עוזב אותך.",
        "קח את המחברת. תגיד לי מה באמת קרה לך היום.",
        "לפני הכל — תכתוב. אני רוצה לשמוע ממך, לא מהדחף."
    )

    private val ACTION_SECOND = listOf(
        "קום. נעליים. אנחנו יוצאים.",
        "עכשיו הגוף מדבר. תזוז, ואני נרגע.",
        "תצא החוצה. אני אשתוק ברגע שתזוז."
    )

    fun interceptLine(c: MentorContext): String {
        val night = c.hour >= 23 || c.hour < 5
        val second = c.attempt >= 2

        val open = when {
            second -> OPEN_SECOND.random()
            night -> OPEN_NIGHT.random()
            else -> OPEN_FIRST.random()
        }

        val truth = if (c.days >= 3 && Math.random() < 0.5) {
            TRUTH_STREAK.random().replace("{days}", c.days.toString())
        } else {
            TRUTH.random()
        }

        val action = if (second) ACTION_SECOND.random() else ACTION_FIRST.random()
        return "$open $truth $action"
    }

    fun ownWords(c: MentorContext): String? {
        return if (c.reasons.isNotEmpty()) c.reasons.random() else null
    }

    fun getLocalMentorReply(userText: String, reasons: List<String>, days: Int, mode: String = "coach"): String {
        val t = userText.trim().lowercase()
        val reasonQuote = reasons.firstOrNull()?.let { " זכור למה התחלת: \"$it\"." } ?: ""

        return when (mode) {
            "warrior" -> when {
                t.contains("קשה") || t.contains("דחף") ->
                    "קום מהמיטה/כיסא ברגע זה. שים את הטלפון בחדר השני. רד ל-25 שכיבות סמיכה עכשיו. האנרגיה הזו שייכת לבנייה שלך, לא לבריחה!"
                t.contains("נכשלתי") || t.contains("נפלתי") ->
                    "בלי רחמים עצמיים. גבר לא שוכב באשפה. קום, שטוף פנים במים קפואים, תיישר גב ותחזור לקרב. שום דבר לא אבוד."
                t.contains("למה") || t.contains("התחלתי") ->
                    "כי נמאס לך להיות צופה פסיבי בחיים שלך! אתה רוצה להיות גבר של פלדה, חזק, ממוקד ומכבד.$reasonQuote"
                t.contains("עייף") || t.contains("לילה") ->
                    "עייפות היא פיתיון של הרגלים חלשים. שים את הטלפון רחוק ולך לישון עכשיו בלי מסכים. פקודה."
                t.contains("בודד") || t.contains("לבד") ->
                    "בדידות מתגברת בעשייה ולא בגלילה. צא החוצה, תעשה הליכה זריזה ברחוב או תתקשר לחבר טוב עכשיו."
                else ->
                    "אל תדבר הרבה — תפעל. מה הפעולה הפיזית או העסקית שאתה הולך לבצע ב-10 הדקות הקרובות?"
            }

            "compassion" -> when {
                t.contains("קשה") || t.contains("דחף") ->
                    "אני שומע אותך אחי. הדחף הזה הוא רק גל של דופמין שמשתוקק להקלה. שים יד על החזה, קח 3 נשימות איטיות עמוקות. אתה בטוח, ואתה חופשי לבחור אחרת."
                t.contains("נכשלתי") || t.contains("נפלתי") ->
                    "שחרר את הבושה. בושה היא האויב הגדול ביותר של ההחלמה. נפילה היא נקודת מידע, לא זהות. מה שנבנה ב-$days הימים עדיין קיים במוח שלך. בוא נמשיך יחד."
                t.contains("למה") || t.contains("התחלתי") ->
                    "התחלת מתוך אהבה לעצמך, למשפחה ולעתיד שלך. כדי להרגיש שוב נוכח בחיים האמיתיים ולהביט במראה בגאווה.$reasonQuote"
                t.contains("עייף") || t.contains("לחץ") ->
                    "הגוף שלך פשוט זקוק למנוחה, חום ורוגע. שתה תה חם, כבה אורות ותן לעצמך לנוח בלי ייסורי מצפון."
                t.contains("בודד") ->
                    "זה טבעי להרגיש בודד לפעמים. המסך רק מעמיק את הריקנות. אני כאן מקשיב לך, ואתה ראוי לקשרים אמיתיים."
                else ->
                    "אני איתך בכל שלב בדרך. קח נשימה עמוקה. ספר לי עוד על מה שאתה חווה עכשיו."
            }

            else -> // "coach" (Balanced, practical, insightful)
                when {
                    t.contains("קשה") || t.contains("דחף") ->
                        "הגל הזה מגיע לשיא ויורד מעצמו תוך 15-20 דקות. הגוף שלך מנסה לפתור אי נוחות רגעית. בוא נבצע 'גלישת דחף': כוס מים גדולה, 2 דקות נשימה, ומעבר לפעולה הבאה.$reasonQuote"
                    t.contains("נכשלתי") || t.contains("נפלתי") ->
                        "בלי דרמה ובלי הלקאה. בוא ננתח כמאמנים: מה היה הטריגר המדויק? עייפות? שעה מאוחרת? טלפון במיטה? נסגור את הפרצה הזו עכשיו ונחזור לשמור על השרשרת."
                    t.contains("למה") || t.contains("התחלתי") ->
                        "התחלת כדי שהראש שלך יהיה צלול לנהל עסק, להתאמן בעוצמה, ולהיות גבר שסומכים עליו.$reasonQuote"
                    t.contains("עייף") || t.contains("שעמום") ->
                        "שעמום ועייפות הם הטריגרים הנפוצים ביותר (65% מהדחפים). המוח מחפש גירוי זול. החלף אותו בגירוי אמיתי: הליכה, מקלחת קרה, או שינה מיידית."
                    t.contains("עסק") || t.contains("מטרה") ->
                        "מצוין. כל יום נקי מחזיר לך בממוצע שעתיים של ריכוז וביטחון עצמי. בחר משימת עסק אחת של 15 דקות ובצע אותה עכשיו."
                    else ->
                        "אני שומע אותך. בוא נתמקד במטרה שלך: מה הפעולה המדויקת ביותר שתקדם אותך היום לכיוון שאתה רוצה לבנות?"
                }
        }
    }
}
